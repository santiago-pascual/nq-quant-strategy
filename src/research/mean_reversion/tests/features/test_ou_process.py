# MEAN REVERSION SPEED
# ============================================================


def test_mean_reversion_speed_rejects_invalid_phi():

    df = pd.DataFrame(
        {
            "ar1_coefficient_30": [
                -0.5,
                0.0,
                1.0,
                1.5,
            ],
            "ar1_coefficient_60": [
                -0.5,
                0.0,
                1.0,
                1.5,
            ],
            "ar1_coefficient_120": [
                -0.5,
                0.0,
                1.0,
                1.5,
            ],
        }
    )

    result = add_mean_reversion_speed(df)

    for window in (30, 60, 120):
        assert result[f"mean_reversion_speed_{window}"].isna().all()


# ============================================================
# HALF-LIFE
# ============================================================


def test_half_life():

    speed = -np.log(0.5)

    df = pd.DataFrame(
        {
            "mean_reversion_speed_30": [speed],
            "mean_reversion_speed_60": [speed],
            "mean_reversion_speed_120": [speed],
        }
    )

    result = add_half_life(df)

    for window in (30, 60, 120):
        assert np.isclose(
            result.loc[
                0,
                f"half_life_{window}",
            ],
            1.0,
        )


# ============================================================
# OU RESIDUAL
# ============================================================


def test_ou_residual(
    price_data,
):

    result = add_ou_residual(price_data)

    expected_mean = np.mean(price_data["close"].iloc[1:31])

    expected = price_data.loc[30, "close"] - expected_mean

    assert np.isclose(
        result.loc[
            30,
            "ou_residual_30",
        ],
        expected,
    )


# ============================================================
# NORMALIZED RESIDUAL
# ============================================================


def test_normalized_ou_residual(
    price_data,
):

    df = add_ou_residual(price_data)

    result = add_normalized_ou_residual(df)

    rolling_std = price_data["close"].rolling(30).std().iloc[30]

    expected = (
        result.loc[
            30,
            "ou_residual_30",
        ]
        / rolling_std
    )

    assert np.isclose(
        result.loc[
            30,
            "normalized_ou_residual_30",
        ],
        expected,
    )


