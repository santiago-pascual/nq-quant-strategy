# ============================================================
# NO LOOK-AHEAD
# ============================================================


def test_ou_features_do_not_depend_on_future_data():

    df_original = pd.DataFrame(
        {
            "close": np.linspace(
                100.0,
                150.0,
                150,
            )
        }
    )

    df_modified = df_original.copy()

    # Change only future data.
    df_modified.loc[
        149,
        "close",
    ] = 1000.0

    original = add_ou_features(df_original)

    modified = add_ou_features(df_modified)

    for column in [
        "autocorrelation_30",
        "ar1_coefficient_30",
        "mean_reversion_speed_30",
        "half_life_30",
        "ou_residual_30",
        "normalized_ou_residual_30",
    ]:
        assert np.isclose(
            original.loc[100, column],
            modified.loc[100, column],
            equal_nan=True,
        )
